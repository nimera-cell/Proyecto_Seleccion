    private void btnAgregarLineaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarLineaActionPerformed
        // TODO add your handling code here:
                if (cmbParametro.getSelectedItem() == null || txtCalificacion.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un parámetro y escriba una calificación.");
            return;
        }

        // Extraer código y nombre de: "1 - Prueba Técnica Java (Max: 50.0)"
        String seleccionado = cmbParametro.getSelectedItem().toString();
        String[] partes = seleccionado.split(" - ");
        String codigoParam = partes[0];
        String nombreParam = partes[1];
        String calificacion = txtCalificacion.getText().trim();

        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblDetalle.getModel();
        modelo.addRow(new Object[]{codigoParam, nombreParam, calificacion});

        txtCalificacion.setText("");
    }//GEN-LAST:event_btnAgregarLineaActionPerformed

    private void btnContratarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnContratarActionPerformed
        // TODO add your handling code here:
                String cantStr = javax.swing.JOptionPane.showInputDialog(this, "¿Cuántos mejores candidatos desea contratar?");
        if (cantStr == null || cantStr.trim().isEmpty()) return;

        String sueldoStr = javax.swing.JOptionPane.showInputDialog(this, "Ingrese el sueldo base para los contratados:");
        if (sueldoStr == null || sueldoStr.trim().isEmpty()) return;

        try {
            int cantidad = Integer.parseInt(cantStr.trim());
            double sueldo = Double.parseDouble(sueldoStr.trim());

            boolean exito = ProcesoServicio.ejecutarContratacion(cantidad, sueldo);
            if (exito) {
                javax.swing.JOptionPane.showMessageDialog(this, "¡Proceso de contratación ejecutado! Los " + cantidad + " mejores pasaron a Nómina.");
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor ingrese valores numéricos válidos.", "Error de formato", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnContratarActionPerformed

