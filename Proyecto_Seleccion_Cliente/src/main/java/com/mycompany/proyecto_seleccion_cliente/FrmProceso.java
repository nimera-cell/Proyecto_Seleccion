    private void btnGuardarEvaluacionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarEvaluacionActionPerformed
        // TODO add your handling code here:
                if (cmbCandidato.getSelectedItem() == null || tblDetalle.getRowCount() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un candidato y agregue al menos una calificación.");
            return;
        }

        // Extraer solo la cédula de: "1725489630 - Juan Perez"
        String candidatoSel = cmbCandidato.getSelectedItem().toString();
        String cedula = candidatoSel.split(" - ")[0];

        // Empaquetar detalles: "1,45;2,28"
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < tblDetalle.getRowCount(); i++) {
            String codParam = tblDetalle.getValueAt(i, 0).toString();
            String nota = tblDetalle.getValueAt(i, 2).toString();
            sb.append(codParam).append(",").append(nota);
            if (i < tblDetalle.getRowCount() - 1) {
                sb.append(";");
            }
        }

        boolean exito = ProcesoServicio.registrarEvaluacion(cedula, sb.toString());
        if (exito) {
            javax.swing.JOptionPane.showMessageDialog(this, "¡Evaluación guardada exitosamente en Oracle!");
            ((javax.swing.table.DefaultTableModel) tblDetalle.getModel()).setRowCount(0);
        }
    }//GEN-LAST:event_btnGuardarEvaluacionActionPerformed

