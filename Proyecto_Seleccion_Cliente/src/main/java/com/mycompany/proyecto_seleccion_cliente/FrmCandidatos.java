    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
            // Capturar los datos ingresados por el usuario en la interfaz
    String cedula = txtCedula.getText().trim();
    String nombre = txtNombre.getText().trim();
    String fecha = txtFecha.getText().trim();

    // Validar que los campos no estén vacíos
    if (cedula.isEmpty() || nombre.isEmpty() || fecha.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, llene todos los campos obligatorios.", "Campos Vacíos", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Llamar al servicio por sockets para insertar en Oracle
    boolean exito = com.mycompany.proyecto_seleccion_cliente.CandidatoServicio.insertarCandidato(cedula, nombre, fecha);

    if (exito) {
        javax.swing.JOptionPane.showMessageDialog(this, "¡Candidato registrado exitosamente!");
        
        // Limpiar los cuadros de texto para un nuevo registro
        txtCedula.setText("");
        txtNombre.setText("");
        txtFecha.setText("");
        
        // Refrescar automáticamente la tabla para mostrar el nuevo candidato
        com.mycompany.proyecto_seleccion_cliente.CandidatoServicio.cargarTablaCandidatos(tblCandidatos);
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

