    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
            String nombre = txtNombreParametro.getText().trim();
    String puntaje = txtPuntajeMaximo.getText().trim();

    if (nombre.isEmpty() || puntaje.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, llene todos los campos.", "Campos Vacíos", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    boolean exito = com.mycompany.proyecto_seleccion_cliente.ParametroServicio.insertarParametro(nombre, puntaje);

    if (exito) {
        javax.swing.JOptionPane.showMessageDialog(this, "¡Parámetro registrado con éxito!");
        txtNombreParametro.setText("");
        txtPuntajeMaximo.setText("");
        com.mycompany.proyecto_seleccion_cliente.ParametroServicio.cargarTablaParametros(tblParametros);
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

